"""On-policy data aggregation (DAgger-style) for the travel-time predictor.

    python -m predictor.aggregate --round 1

Round 0 data came from the distance policy only, so the model never saw the trips its own
assignments create. Round r:
  1. collect trips with the round r-1 learned policy on the same training/validation configs
     (training layout families only; held-out families are collected only to measure accuracy)
  2. retrain the MLP on all rounds' training data (3 seeds, selected on all rounds' validation data)
  3. report accuracy on held-out trips generated by the learned policy (the distribution that matters)
Writes results/data_r{r}/, results/models/mlp_r{r}.json, results/summary/aggregate_r{r}.json.
"""

from __future__ import annotations

import argparse
import json
from multiprocessing import Pool
from pathlib import Path

import numpy as np

from planners.policies import LearnedPolicy
from predictor.dataset import HORIZON, configs
from predictor.features import FEATURES
from predictor.model import TravelTimeModel, fit_mlp
from predictor.train import report
from sim.engine import Simulation
from sim.layout import spec
from sim.scenario import Scenario, with_faults

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "results/models"


def data_dir(r: int) -> Path:
    return ROOT / ("results/data" if r == 0 else f"results/data_r{r}")


def model_name(r: int) -> str:
    return "mlp" if r == 0 else f"mlp_r{r}"


def collect(cfg: dict) -> list[dict]:
    sc = Scenario(spec(cfg["family"], cfg["seed"]), n_robots=cfg["n_robots"], horizon=HORIZON,
                  order_rate=cfg["rate"], seed=cfg["seed"] * 1000 + cfg["n_robots"] + int(cfg["rate"] * 10))
    if cfg["faults"]:
        sc = with_faults(sc)
    policy = LearnedPolicy(TravelTimeModel.load(MODELS / f"{cfg['model']}.json"))
    sim = Simulation(sc, policy, record_trips=True)
    sim.run()
    return [{**t, "family": cfg["family"], "seed": cfg["seed"]} for t in sim.trips]


def save(split: str, trips: list[dict], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(out / f"{split}.npz", X=np.array([[t[f] for f in FEATURES] for t in trips], dtype=np.float64),
                        y=np.array([t["actual"] for t in trips], dtype=np.float64),
                        kind=np.array([t["kind"] for t in trips]), family=np.array([t["family"] for t in trips]))


def load(split: str, rounds: list[int]):
    parts = [np.load(data_dir(r) / f"{split}.npz") for r in rounds]
    X = np.vstack([p["X"] for p in parts])
    rows = [dict(zip(FEATURES, x)) for x in X]
    return rows, np.concatenate([p["y"] for p in parts]), np.concatenate([p["kind"] for p in parts]), X[:, FEATURES.index("dist")]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--round", type=int, required=True)
    p.add_argument("--workers", type=int, default=10)
    args = p.parse_args()
    r = args.round
    prev = model_name(r - 1)
    for split in ("train", "val", "heldout"):
        jobs = [{**c, "model": prev} for c in configs(split)]
        with Pool(args.workers) as pool:
            trips = [t for chunk in pool.map(collect, jobs) for t in chunk]
        save(split, trips, data_dir(r))
        print(f"round {r} {split}: {len(trips)} trips collected with {prev}")

    rounds = list(range(r + 1))
    tr_rows, tr_y, _, _ = load("train", rounds)
    va_rows, va_y, _, _ = load("val", rounds)
    best = None
    for seed in range(3):
        model, info = fit_mlp(tr_rows, tr_y, va_rows, va_y, seed=seed)
        if best is None or info["best_val_mse_log"] < best[1]:
            best = (model, info["best_val_mse_log"], seed)
    best[0].save(MODELS / f"{model_name(r)}.json")

    # Accuracy on the distribution that matters: held-out layouts, trips made by the learned policy.
    h_rows, h_y, h_kind, h_dist = load("heldout", [r])
    out = {"round": r, "trained_on_rounds": rounds, "n_train": len(tr_y), "selected_seed": best[2],
           "heldout_onpolicy_trips": len(h_y),
           "accuracy_on_learned_policy_trips": {
               "distance": report(h_dist, h_y, h_kind, h_dist),
               model_name(r - 1): report(TravelTimeModel.load(MODELS / f"{prev}.json").predict(h_rows), h_y, h_kind, h_dist),
               model_name(r): report(best[0].predict(h_rows), h_y, h_kind, h_dist)}}
    (ROOT / f"results/summary/aggregate_r{r}.json").write_text(json.dumps(out, indent=1))
    for name, rep in out["accuracy_on_learned_policy_trips"].items():
        print(f"{name:8} MAE {rep['mae']:6} congested {rep['mae_congested']:6} rank-corr {rep['rank_corr_excess']}")


if __name__ == "__main__":
    main()
